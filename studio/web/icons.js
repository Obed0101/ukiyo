/**
 * A lucide icon as an inline SVG that takes the text color. Decorative unless a label is given.
 * @param {string} name
 * @param {{ size?: number, label?: string, strokeWidth?: number }} [options]
 * @returns {SVGSVGElement}
 */
export function icon(name, { size = 16, label, strokeWidth = 1.5 } = {}) {
  const nodes = ICONS[name];
  if (!nodes) throw new RangeError(`[STUDIO]: unknown icon "${name}"; add it to studio/web/icons.js`);
  const svg = document.createElementNS(SVG, "svg");
  for (const [key, value] of Object.entries({
    width: size, height: size, viewBox: "0 0 24 24", fill: "none", stroke: "currentColor",
    "stroke-width": strokeWidth, "stroke-linecap": "round", "stroke-linejoin": "round", class: "icon",
  })) svg.setAttribute(key, String(value));
  if (label) {
    svg.setAttribute("role", "img");
    svg.setAttribute("aria-label", label);
  } else {
    svg.setAttribute("aria-hidden", "true");
  }
  for (const [tag, attributes] of nodes) {
    const child = document.createElementNS(SVG, tag);
    for (const [key, value] of Object.entries(attributes)) child.setAttribute(key, value);
    svg.append(child);
  }
  return svg;
}
