using System.Globalization;
using System.Numerics;
using System.Text;

namespace Ukiyo.Import;

/// <summary>
/// Writes the generated C# for a set of meshes: one nested static class per mesh with its counts, bounds, content hash
/// and <c>Create()</c>. Vertex data are <c>ReadOnlySpan&lt;float&gt;</c>/<c>&lt;uint&gt;</c> over constant arrays, which
/// the compiler stores in the assembly's data section (no parsing, no reflection; NativeAOT and WebAssembly keep them).
/// Floats are written with the shortest round-trip form, so the compiled values are the imported bits exactly.
/// Line endings are always '\n'.
/// </summary>
internal static class MeshCodeEmitter
{
    public sealed record Input(string ClassName, string Namespace, IReadOnlyList<ImportedMesh> Meshes, string ContentHash, IReadOnlyList<(string Path, string Sha256)> Sources, MeshImportRequest Request);

    public static string Emit(Input input)
    {
        var meshes = input.Meshes;
        var code = new StringBuilder(4096 + meshes.Sum(m => m.VertexCount * 120 + m.Data.Indices.Length * 8));
        void Line(string text = "") => code.Append(text).Append('\n');

        Line("// <auto-generated>");
        Line($"//   ukiyo-import mesh v{MeshImporter.Version} (glTF 2.0). Do not edit: change the source model and regenerate.");
        if (input.Request.RegenerateCommand is { } command)
        {
            Line($"//   Regenerate: {command}");
        }

        Line($"//   Options: normals={Option(input.Request.Normals)} doubleSided={Option(input.Request.DoubleSided)}");
        Line("//   Sources (SHA-256):");
        var pathWidth = input.Sources.Max(s => s.Path.Length);
        foreach (var (path, sha) in input.Sources)
        {
            Line($"//     {path.PadRight(pathWidth)}  {sha}");
        }

        Line("// </auto-generated>");
        Line("#nullable enable");
        Line();
        Line("using System.Numerics;");
        Line("using Ukiyo.Rendering;");
        Line();
        Line($"namespace {input.Namespace};");
        Line();
        Line("/// <summary>");
        Line($"/// Imported meshes: {meshes.Count} mesh(es), {meshes.Sum(m => m.VertexCount)} vertices, {meshes.Sum(m => m.TriangleCount)} triangles, in engine conventions (meters,");
        Line("/// right-handed +Y up, counter-clockwise front faces, linear RGB vertex colors with the glTF base color baked in).");
        Line("/// The geometry is compiled in: nothing is parsed or read from disk at runtime. Draw with a material whose base color");
        Line("/// is white and that uses vertex colors, e.g. <c>new MaterialData(Vector4.One, UseVertexColors: true) { Lit = true }</c>.");
        Line("/// </summary>");
        Line($"public static class {input.ClassName}");
        Line("{");
        Line($"    public const int Count = {meshes.Count};");
        Line($"    public const int VertexCount = {meshes.Sum(m => m.VertexCount)};");
        Line($"    public const int TriangleCount = {meshes.Sum(m => m.TriangleCount)};");
        Line();
        Line("    /// <summary>SHA-256 of every mesh's name and content hash (see docs/assets.md). Changes only when the game's data does.</summary>");
        Line($"    public const string ContentHash = \"{input.ContentHash}\";");
        Line();
        Line("    /// <summary>Mesh names (the model file names without extension), sorted.</summary>");
        Line($"    public static IReadOnlyList<string> Names {{ get; }} = [{string.Join(", ", meshes.Select(m => $"\"{m.Name}\""))}];");
        Line();
        Line("    /// <summary>A new <see cref=\"MeshData\"/> for the mesh with this name (one of <see cref=\"Names\"/>).</summary>");
        Line("    public static MeshData Create(string name) => name switch");
        Line("    {");
        foreach (var mesh in meshes)
        {
            Line($"        {mesh.MemberName}.Name => {mesh.MemberName}.Create(),");
        }

        Line($"        _ => throw new ArgumentOutOfRangeException(nameof(name), name, \"[IMPORT]: {input.ClassName} has no mesh with this name; see {input.ClassName}.Names\"),");
        Line("    };");
        foreach (var mesh in meshes)
        {
            Line();
            EmitMesh(code, mesh);
        }

        Line();
        Line("    private static MeshData Build(ReadOnlySpan<float> positions, ReadOnlySpan<float> colors, ReadOnlySpan<float> normals, ReadOnlySpan<uint> indices)");
        Line("    {");
        Line("        var vertices = new VertexPositionColor[positions.Length / 3];");
        Line("        for (var i = 0; i < vertices.Length; i++)");
        Line("        {");
        Line("            vertices[i] = new VertexPositionColor(new Vector3(positions[3 * i], positions[3 * i + 1], positions[3 * i + 2]), new Vector3(colors[3 * i], colors[3 * i + 1], colors[3 * i + 2]));");
        Line("        }");
        Line();
        Line("        Vector3[]? normalArray = null;");
        Line("        if (!normals.IsEmpty)");
        Line("        {");
        Line("            normalArray = new Vector3[vertices.Length];");
        Line("            for (var i = 0; i < normalArray.Length; i++)");
        Line("            {");
        Line("                normalArray[i] = new Vector3(normals[3 * i], normals[3 * i + 1], normals[3 * i + 2]);");
        Line("            }");
        Line("        }");
        Line();
        Line("        return new MeshData(vertices, indices.ToArray()) { Normals = normalArray };");
        Line("    }");
        Line("}");
        return code.ToString();
    }

    private static void EmitMesh(StringBuilder code, ImportedMesh mesh)
    {
        void Line(string text = "") => code.Append(text).Append('\n');
        var hasNormals = mesh.Data.Normals is not null;
        Line($"    /// <summary>Mesh \"{mesh.Name}\": {mesh.VertexCount} vertices, {mesh.TriangleCount} triangles, {(hasNormals ? "with normals (lit or unlit)" : "without normals (unlit only)")}.</summary>");
        Line($"    public static class {mesh.MemberName}");
        Line("    {");
        Line($"        public const string Name = \"{mesh.Name}\";");
        Line($"        public const int VertexCount = {mesh.VertexCount};");
        Line($"        public const int TriangleCount = {mesh.TriangleCount};");
        Line($"        public const bool HasNormals = {(hasNormals ? "true" : "false")};");
        Line($"        public const string ContentHash = \"{mesh.ContentHash}\";");
        Line();
        Line("        /// <summary>Axis-aligned bounds of the positions, in meters (object space).</summary>");
        Line($"        public static Vector3 BoundsMin => new({Float(mesh.BoundsMin.X)}, {Float(mesh.BoundsMin.Y)}, {Float(mesh.BoundsMin.Z)});");
        Line($"        public static Vector3 BoundsMax => new({Float(mesh.BoundsMax.X)}, {Float(mesh.BoundsMax.Y)}, {Float(mesh.BoundsMax.Z)});");
        Line();
        Line("        /// <summary>A new mesh with its own arrays (pass it to <c>GameContext.CreateMesh</c> once, in Initialize).</summary>");
        Line($"        public static MeshData Create() => Build(Positions, Colors, {(hasNormals ? "Normals" : "[]")}, Indices);");
        Line();
        Vectors(code, "Positions", mesh.Data.Vertices.Select(v => v.Position));
        Line();
        Vectors(code, "Colors", mesh.Data.Vertices.Select(v => v.Color));
        if (mesh.Data.Normals is { } normals)
        {
            Line();
            Vectors(code, "Normals", normals);
        }

        Line();
        Line("        private static ReadOnlySpan<uint> Indices => new uint[]");
        Line("        {");
        var indices = mesh.Data.Indices;
        for (var i = 0; i < indices.Length; i += 3)
        {
            Line($"            {indices[i]}, {indices[i + 1]}, {indices[i + 2]},");
        }

        Line("        };");
        Line("    }");
    }

    /// <summary>One vector per line, x, y, z.</summary>
    private static void Vectors(StringBuilder code, string name, IEnumerable<Vector3> values)
    {
        code.Append("        private static ReadOnlySpan<float> ").Append(name).Append(" => new float[]\n        {\n");
        foreach (var v in values)
        {
            code.Append("            ").Append(Float(v.X)).Append(", ").Append(Float(v.Y)).Append(", ").Append(Float(v.Z)).Append(",\n");
        }

        code.Append("        };\n");
    }

    /// <summary>Shortest round-trip float literal: the C# compiler reads back exactly these bits (including −0).</summary>
    internal static string Float(float value) => value.ToString("R", CultureInfo.InvariantCulture) + "f";

    internal static string Option(NormalsMode mode) => mode switch
    {
        NormalsMode.Required => "required",
        NormalsMode.Flat => "flat",
        _ => "none",
    };

    internal static string Option(DoubleSidedMode mode) => mode == DoubleSidedMode.Cull ? "cull" : "reject";
}
