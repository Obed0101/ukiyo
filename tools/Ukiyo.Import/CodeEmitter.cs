using System.Globalization;
using System.Text;

namespace Ukiyo.Import;

/// <summary>
/// Writes the generated C# for one atlas. Pixels become a <c>ReadOnlySpan&lt;byte&gt;</c> over a constant array, which
/// the compiler stores in the assembly's data section: no decoding, no allocation until a texture is created, and
/// nothing reflection-based, so NativeAOT and WebAssembly trimming keep it as is. Line endings are always '\n'.
/// </summary>
internal static class CodeEmitter
{
    private const int BytesPerLine = 32;

    public sealed record Input(string ClassName, string Namespace, PackedAtlas Atlas, string ContentHash, IReadOnlyList<(string Path, string Sha256)> Sources, string? RegenerateCommand);

    public static string Emit(Input input)
    {
        var atlas = input.Atlas;
        var code = new StringBuilder(atlas.Rgba.Length * 6 + 4096);
        void Line(string text = "") => code.Append(text).Append('\n');

        Line("// <auto-generated>");
        Line($"//   ukiyo-import v{AtlasImporter.FormatVersion}. Do not edit: change the source art and regenerate.");
        if (input.RegenerateCommand is { } command)
        {
            Line($"//   Regenerate: {command}");
        }

        Line("//   Sources (SHA-256):");
        var pathWidth = input.Sources.Max(s => s.Path.Length);
        foreach (var (path, sha) in input.Sources)
        {
            Line($"//     {path.PadRight(pathWidth)}  {sha}");
        }

        Line("// </auto-generated>");
        Line("#nullable enable");
        Line();
        Line("using Ukiyo;");
        Line("using Ukiyo.Rendering;");
        Line();
        Line($"namespace {input.Namespace};");
        Line();
        Line($"/// <summary>");
        Line($"/// Imported atlas, {atlas.Width}x{atlas.Height} RGBA8 (sRGB color, straight alpha), {atlas.Frames.Count} frame(s) with {atlas.Extrude} px edge");
        Line($"/// extrusion, {atlas.Animations.Count} animation(s). The pixels are compiled in: nothing is decoded or read from disk at runtime.");
        Line($"/// </summary>");
        Line($"public static class {input.ClassName}");
        Line("{");
        Line($"    public const int Width = {atlas.Width};");
        Line($"    public const int Height = {atlas.Height};");
        Line($"    public const int Extrude = {atlas.Extrude};");
        Line();
        Line("    /// <summary>SHA-256 of size, frames, animations and pixels (see docs/assets.md). Changes only when the game's data does.</summary>");
        Line($"    public const string ContentHash = \"{input.ContentHash}\";");
        Line();
        Line("    /// <summary>Frame rectangles in pixels (y down), sorted by name.</summary>");
        Line("    public static IReadOnlyList<AtlasFrame> Frames { get; } =");
        Line("    [");
        foreach (var f in atlas.Frames)
        {
            Line($"        new(\"{f.Name}\", {f.X}, {f.Y}, {f.Width}, {f.Height}),");
        }

        Line("    ];");
        Line();
        Line("    /// <summary>Animations, sorted by name; frame order is playback order.</summary>");
        Line("    public static IReadOnlyList<AtlasAnimation> Animations { get; } =");
        Line("    [");
        foreach (var a in atlas.Animations)
        {
            var frames = string.Join(", ", a.Frames.Select(n => $"\"{n}\""));
            Line($"        new(\"{a.Name}\", [{frames}], {Float(a.FramesPerSecond)}, {(a.Loop ? "true" : "false")}),");
        }

        Line("    ];");
        Line();
        Line("    /// <summary>The texture to upload (copies the compiled pixels once).</summary>");
        Line("    public static TextureData Texture(TextureFilter filter = TextureFilter.Nearest) => new(Width, Height, Rgba.ToArray(), filter);");
        Line();
        Line("    /// <summary>Uploads the texture and returns the sheet with every frame and animation by name.</summary>");
        Line("    public static SpriteSheet Load(GameContext context, TextureFilter filter = TextureFilter.Nearest) =>");
        Line("        SpriteSheet.FromAtlas(context.CreateTexture(Texture(filter)), Width, Height, Frames, Animations);");
        Line();
        Line("    /// <summary>RGBA8 pixels, rows top to bottom, sRGB-encoded color, straight alpha: the CreateTexture contract.</summary>");
        Line("    public static ReadOnlySpan<byte> Rgba => new byte[]");
        Line("    {");
        for (var offset = 0; offset < atlas.Rgba.Length; offset += BytesPerLine)
        {
            code.Append("       ");
            var end = Math.Min(atlas.Rgba.Length, offset + BytesPerLine);
            for (var i = offset; i < end; i++)
            {
                code.Append(" 0x").Append(atlas.Rgba[i].ToString("X2", CultureInfo.InvariantCulture)).Append(',');
            }

            code.Append('\n');
        }

        Line("    };");
        Line("}");
        return code.ToString();
    }

    private static string Float(float value) => value.ToString("R", CultureInfo.InvariantCulture) + "f";
}
